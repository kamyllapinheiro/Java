package org.example.aulaScanner5;

public class questão2 {
    public static void main(String[] args) {

        for (int i = 1; i < 16; i++) {
            if (i % 2 == 0)
                System.out.println(i + " é par");
            else {
                System.out.println(i + " é impar");
            }


        }
    }
}